function revealTarget(hash,scroll=false) {
 if(!hash || hash==='#')return;
 let target; try {target=document.getElementById(decodeURIComponent(hash.slice(1)));}catch{return;}
 if(!target)return;
 if(target.hidden || target.closest('[hidden]'))resetFilters();
 if(scroll)requestAnimationFrame(()=>{target.scrollIntoView({block:'start',behavior:matchMedia('(prefers-reduced-motion: reduce)').matches?'instant':'smooth'});if(!target.hasAttribute('tabindex'))target.setAttribute('tabindex','-1');target.focus({preventScroll:true});});
}
